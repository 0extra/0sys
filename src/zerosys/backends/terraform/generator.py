from __future__ import annotations

from zerosys.core.config.schema import Config, InfrastructureConfig

TERRAFORM_HEADER = "# Generated by 0sys. Do not edit manually.\n\n"
HCL_INDENT = "  "


class TerraformError(Exception):
    pass


class TerraformGenerator:
    def generate(self, config: Config) -> dict[str, str]:
        if config.infrastructure is None:
            raise TerraformError("config has no 'infrastructure' section; nothing to generate")
        return {
            "main.tf": self._main_tf(config),
            "variables.tf": self._variables_tf(config),
            "outputs.tf": self._outputs_tf(config),
        }

    def _main_tf(self, config: Config) -> str:
        infra = config.infrastructure
        assert infra is not None
        if infra.provider == "hetzner":
            return self._hetzner_main(config, infra)
        if infra.provider == "digitalocean":
            return self._digitalocean_main(config, infra)
        raise TerraformError(f"unsupported provider: {infra.provider}")

    def _hetzner_main(self, config: Config, infra: InfrastructureConfig) -> str:
        name = infra.name or (config.server.hostname if config.server else None) or "0sys-server"
        lines: list[str] = [TERRAFORM_HEADER]
        lines.append("terraform {")
        lines.append(f"{HCL_INDENT}required_providers {{")
        lines.append(f"{HCL_INDENT}{HCL_INDENT}hcloud = {{")
        lines.append(f'{HCL_INDENT}{HCL_INDENT}{HCL_INDENT}source  = "hetznercloud/hcloud"')
        lines.append(f'{HCL_INDENT}{HCL_INDENT}{HCL_INDENT}version = "~> 1.45"')
        lines.append(f"{HCL_INDENT}{HCL_INDENT}}}")
        lines.append(f"{HCL_INDENT}}}")
        lines.append("}")
        lines.append("")
        lines.append('provider "hcloud" {}')
        lines.append("")
        lines.append('resource "hcloud_server" "main" {')
        lines.append(f'{HCL_INDENT}name        = "{name}"')
        lines.append(f'{HCL_INDENT}server_type = "{infra.server_type}"')
        lines.append(f'{HCL_INDENT}image       = "{infra.image}"')
        lines.append(f'{HCL_INDENT}location    = "{infra.region}"')
        if infra.ssh_keys:
            keys = ", ".join(f'"{k}"' for k in infra.ssh_keys)
            lines.append(f"{HCL_INDENT}ssh_keys    = [{keys}]")
        lines.append("")
        lines.append(f"{HCL_INDENT}labels = {{")
        lines.append(f'{HCL_INDENT}{HCL_INDENT}managed_by = "0sys"')
        for tag in infra.tags:
            key, _, value = tag.partition(":")
            if not value:
                value = "true"
            lines.append(f'{HCL_INDENT}{HCL_INDENT}{key} = "{value}"')
        lines.append(f"{HCL_INDENT}}}")
        lines.append("}")
        lines.append("")
        return "\n".join(lines)

    def _digitalocean_main(self, config: Config, infra: InfrastructureConfig) -> str:
        name = infra.name or (config.server.hostname if config.server else None) or "0sys-server"
        lines: list[str] = [TERRAFORM_HEADER]
        lines.append("terraform {")
        lines.append(f"{HCL_INDENT}required_providers {{")
        lines.append(f"{HCL_INDENT}{HCL_INDENT}digitalocean = {{")
        lines.append(f'{HCL_INDENT}{HCL_INDENT}{HCL_INDENT}source  = "digitalocean/digitalocean"')
        lines.append(f'{HCL_INDENT}{HCL_INDENT}{HCL_INDENT}version = "~> 2.34"')
        lines.append(f"{HCL_INDENT}{HCL_INDENT}}}")
        lines.append(f"{HCL_INDENT}}}")
        lines.append("}")
        lines.append("")
        lines.append('provider "digitalocean" {}')
        lines.append("")
        lines.append('resource "digitalocean_droplet" "main" {')
        lines.append(f'{HCL_INDENT}name   = "{name}"')
        lines.append(f'{HCL_INDENT}size   = "{infra.server_type}"')
        lines.append(f'{HCL_INDENT}image  = "{infra.image}"')
        lines.append(f'{HCL_INDENT}region = "{infra.region}"')
        if infra.ssh_keys:
            keys = ", ".join(f'"{k}"' for k in infra.ssh_keys)
            lines.append(f"{HCL_INDENT}ssh_keys = [{keys}]")
        lines.append("")
        tags = ["managed_by:0sys", *infra.tags]
        tags_block = ", ".join(f'"{t}"' for t in tags)
        lines.append(f"{HCL_INDENT}tags = [{tags_block}]")
        lines.append("}")
        lines.append("")
        return "\n".join(lines)

    def _variables_tf(self, config: Config) -> str:
        infra = config.infrastructure
        assert infra is not None
        lines: list[str] = [TERRAFORM_HEADER]
        lines.append('variable "provider_token" {')
        lines.append(f'{HCL_INDENT}description = "API token for {infra.provider}"')
        lines.append(f"{HCL_INDENT}type        = string")
        lines.append(f"{HCL_INDENT}sensitive   = true")
        lines.append("}")
        lines.append("")
        return "\n".join(lines)

    def _outputs_tf(self, config: Config) -> str:
        infra = config.infrastructure
        assert infra is not None
        lines: list[str] = [TERRAFORM_HEADER]
        if infra.provider == "hetzner":
            lines.append('output "server_ip" {')
            lines.append(f"{HCL_INDENT}value       = hcloud_server.main.ipv4_address")
            lines.append(f'{HCL_INDENT}description = "Public IPv4 address of the server"')
            lines.append("}")
            lines.append("")
            lines.append('output "server_id" {')
            lines.append(f"{HCL_INDENT}value       = hcloud_server.main.id")
            lines.append(f'{HCL_INDENT}description = "Numeric ID of the server"')
            lines.append("}")
        else:
            lines.append('output "server_ip" {')
            lines.append(f"{HCL_INDENT}value       = digitalocean_droplet.main.ipv4_address")
            lines.append(f'{HCL_INDENT}description = "Public IPv4 address of the server"')
            lines.append("}")
            lines.append("")
            lines.append('output "server_id" {')
            lines.append(f"{HCL_INDENT}value       = digitalocean_droplet.main.id")
            lines.append(f'{HCL_INDENT}description = "Numeric ID of the server"')
            lines.append("}")
        lines.append("")
        return "\n".join(lines)


def generate_terraform(config: Config) -> dict[str, str]:
    return TerraformGenerator().generate(config)
