from __future__ import annotations

from pathlib import Path

from zerosys.core.config.schema import Config

NIX_HEADER = "# Generated by 0sys. Do not edit manually.\n\n"
INDENT = "  "

DEFAULT_STATE_VERSION = "24.11"


class NixosError(Exception):
    pass


class NixosGenerator:
    def generate(self, config: Config) -> str:
        lines: list[str] = [NIX_HEADER]
        lines.append("{ config, pkgs, ... }:")
        lines.append("")
        lines.append("{")
        self._add_imports(lines)
        self._add_system(lines)
        self._add_hostname(lines, config)
        self._add_timezone(lines, config)
        self._add_locale(lines, config)
        self._add_packages(lines, config)
        self._add_services(lines, config)
        self._add_users(lines, config)
        self._add_firewall(lines, config)
        self._add_files(lines, config)
        lines.append("}")
        lines.append("")
        return "\n".join(lines)

    def _add_imports(self, lines: list[str]) -> None:
        lines.append(f"{INDENT}imports = [")
        lines.append(f"{INDENT}{INDENT}./hardware-configuration.nix")
        lines.append(f"{INDENT}];")
        lines.append("")

    def _add_system(self, lines: list[str]) -> None:
        lines.append(f'{INDENT}system.stateVersion = "{DEFAULT_STATE_VERSION}";')
        lines.append("")

    def _add_hostname(self, lines: list[str], config: Config) -> None:
        if config.server is None or not config.server.hostname:
            return
        lines.append(f'{INDENT}networking.hostName = "{config.server.hostname}";')
        lines.append("")

    def _add_timezone(self, lines: list[str], config: Config) -> None:
        if config.server is None or not config.server.timezone:
            return
        lines.append(f'{INDENT}time.timeZone = "{config.server.timezone}";')
        lines.append("")

    def _add_locale(self, lines: list[str], config: Config) -> None:
        if config.server is None or not config.server.locale:
            return
        lines.append(f'{INDENT}i18n.defaultLocale = "{config.server.locale}";')
        lines.append("")

    def _add_packages(self, lines: list[str], config: Config) -> None:
        if config.packages is None or not config.packages.install:
            return
        lines.append(f"{INDENT}environment.systemPackages = with pkgs; [")
        for pkg in config.packages.install:
            lines.append(f"{INDENT}{INDENT}{pkg}")
        lines.append(f"{INDENT}];")
        lines.append("")

    def _add_services(self, lines: list[str], config: Config) -> None:
        if not config.services:
            return
        emitted = False
        for name in config.services:
            attr = self._service_attribute(name)
            if attr is None:
                lines.append(f"{INDENT}# service '{name}' has no NixOS mapping; skipped")
                continue
            lines.append(f"{INDENT}services.{attr}.enable = true;")
            emitted = True
        if emitted or config.services:
            lines.append("")

    def _service_attribute(self, name: str) -> str | None:
        known: dict[str, str] = {
            "nginx": "nginx",
            "openssh": "openssh",
            "sshd": "openssh",
            "fail2ban": "fail2ban",
            "docker": "docker",
            "postgresql": "postgresql",
            "mysql": "mysql",
            "mariadb": "mysql",
            "redis": "redis",
        }
        return known.get(name)

    def _add_users(self, lines: list[str], config: Config) -> None:
        if not config.users:
            return
        lines.append(f"{INDENT}users.users = {{")
        for user in config.users:
            lines.append(f"{INDENT}{INDENT}{user.name} = {{")
            lines.append(f"{INDENT}{INDENT}{INDENT}isNormalUser = true;")
            if user.groups:
                groups = " ".join(f'"{g}"' for g in user.groups)
                lines.append(f"{INDENT}{INDENT}{INDENT}extraGroups = [ {groups} ];")
            shell_pkg = self._shell_package(user.shell)
            lines.append(f"{INDENT}{INDENT}{INDENT}shell = pkgs.{shell_pkg};")
            if user.ssh_key:
                lines.append(f"{INDENT}{INDENT}{INDENT}openssh.authorizedKeys.keys = [")
                lines.append(f'{INDENT}{INDENT}{INDENT}{INDENT}"{user.ssh_key}"')
                lines.append(f"{INDENT}{INDENT}{INDENT}];")
            lines.append(f"{INDENT}{INDENT}}};")
        lines.append(f"{INDENT}}};")
        lines.append("")

    def _shell_package(self, shell: str) -> str:
        mapping: dict[str, str] = {
            "/bin/bash": "bash",
            "/bin/zsh": "zsh",
            "/bin/sh": "bash",
            "/usr/bin/bash": "bash",
            "/usr/bin/zsh": "zsh",
        }
        return mapping.get(shell, "bash")

    def _add_firewall(self, lines: list[str], config: Config) -> None:
        if config.firewall is None:
            return
        lines.append(f"{INDENT}networking.firewall = {{")
        lines.append(f"{INDENT}{INDENT}enable = true;")
        if config.firewall.allow:
            ports = " ".join(str(p) for p in config.firewall.allow)
            lines.append(f"{INDENT}{INDENT}allowedTCPPorts = [ {ports} ];")
        lines.append(f"{INDENT}}};")
        lines.append("")

    def _add_files(self, lines: list[str], config: Config) -> None:
        if not config.files:
            return
        for entry in config.files:
            etc_name = self._etc_name(entry.dest)
            lines.append(f'{INDENT}environment.etc."{etc_name}" = {{')
            lines.append(f"{INDENT}{INDENT}text = ''")
            content = self._read_local_file(entry.src)
            for line in content.splitlines():
                lines.append(f"{INDENT}{INDENT}{line}")
            lines.append(f"{INDENT}{INDENT}'';")
            lines.append(f'{INDENT}{INDENT}mode = "{entry.mode}";')
            lines.append(f"{INDENT}}};")
        lines.append("")

    def _etc_name(self, dest: str) -> str:
        if dest.startswith("/etc/"):
            return dest[len("/etc/") :]
        return dest.strip("/").replace("/", "-")

    def _read_local_file(self, source: str) -> str:
        path = Path(source).expanduser()
        if not path.exists():
            return f"# source not found: {source}"
        try:
            return path.read_text(encoding="utf-8")
        except OSError:
            return f"# cannot read source: {source}"


def generate_nixos(config: Config) -> str:
    return NixosGenerator().generate(config)
